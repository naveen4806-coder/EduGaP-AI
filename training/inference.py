@app.post("/ml/predict-risk", response_model=RiskPredictionResponse)
def predict_risk(snapshot: StudentFeatureSnapshot):
    global _model, _scaler
    if _model is None or _scaler is None:
        load_artifacts()

    if _model is None or _scaler is None:
        return rule_based_fallback(snapshot)

    try:
        raw_values = [getattr(snapshot, feat) for feat in FEATURE_NAMES]
        feature_matrix = np.array([raw_values], dtype=float)
        scaled_features = _scaler.transform(feature_matrix)

        with torch.no_grad():
            tensor_in = torch.tensor(scaled_features, dtype=torch.float32)
            logits = _model(tensor_in)
            probs = torch.softmax(logits, dim=1).numpy()[0]
            pred_idx = int(np.argmax(probs))

        pred_label = RISK_MAPPING[pred_idx]
        conf = float(round(probs[pred_idx], 4))

        prob_dict = {
            RISK_MAPPING[i]: float(round(probs[i], 4))
            for i in range(len(RISK_MAPPING))
        }

        return RiskPredictionResponse(
            student_id=snapshot.student_id,
            risk_level=pred_label,
            confidence_score=conf,
            probabilities=prob_dict,
            model_version="v1.0.0-production-launch",
            production_ready=True,
            fallback_used=False,
            explanation_factors=generate_explanation_factors(snapshot),
            feature_attributions=generate_attributions(snapshot),
            model_limitation_notice=MODEL_LIMITATION_NOTICE
        )
    except Exception as e:
        print(f"[ERROR] Inference error ({e}). Falling back to rule engine.")
        return rule_based_fallback(snapshot)


@app.post("/ml/predict-risk/batch", response_model=BatchPredictionResponse)
def predict_risk_batch(payload: BatchPredictionRequest):
    global _model, _scaler
    if _model is None or _scaler is None:
        load_artifacts()

    if not payload.students:
        return BatchPredictionResponse(
            cohort_name=payload.cohort_name or "Empty Cohort",
            total_evaluated=0,
            summary={"Low Risk": 0, "Medium Risk": 0, "High Risk": 0},
            model_version="v1.0.0-production-launch",
            predictions=[]
        )

    predictions = []
    summary = {"Low Risk": 0, "Medium Risk": 0, "High Risk": 0}

    # If PyTorch model is ready, vectorize the entire batch
    if _model is not None and _scaler is not None:
        try:
            batch_rows = []
            for s in payload.students:
                batch_rows.append([getattr(s, feat) for feat in FEATURE_NAMES])
            
            feat_mat = np.array(batch_rows, dtype=float)
            scaled = _scaler.transform(feat_mat)

            with torch.no_grad():
                tensor_in = torch.tensor(scaled, dtype=torch.float32)
                logits = _model(tensor_in)
                probs = torch.softmax(logits, dim=1).numpy()
                pred_indices = np.argmax(probs, axis=1)

            for idx, s in enumerate(payload.students):
                p_idx = int(pred_indices[idx])
                label = RISK_MAPPING[p_idx]
                summary[label] = summary.get(label, 0) + 1
                conf = float(round(probs[idx][p_idx], 4))
                prob_dict = {
                    RISK_MAPPING[i]: float(round(probs[idx][i], 4))
                    for i in range(len(RISK_MAPPING))
                }
                predictions.append(RiskPredictionResponse(
                    student_id=s.student_id,
                    risk_level=label,
                    confidence_score=conf,
                    probabilities=prob_dict,
                    model_version="v1.0.0-production-launch",
                    production_ready=True,
                    fallback_used=False,
                    explanation_factors=generate_explanation_factors(s),
                    feature_attributions=generate_attributions(s),
                    model_limitation_notice=MODEL_LIMITATION_NOTICE
                ))

            return BatchPredictionResponse(
                cohort_name=payload.cohort_name or "Classroom Cohort",
                total_evaluated=len(payload.students),
                summary=summary,
                model_version="v1.0.0-production-launch",
                predictions=predictions
            )
        except Exception as batch_err:
            print(f"[ERROR] Batch inference failed ({batch_err}), falling back to iterative evaluation.")

    # Fallback iteration
    for s in payload.students:
        pred = predict_risk(s)
        summary[pred.risk_level] = summary.get(pred.risk_level, 0) + 1
        predictions.append(pred)

    return BatchPredictionResponse(
        cohort_name=payload.cohort_name or "Classroom Cohort",
        total_evaluated=len(payload.students),
        summary=summary,
        model_version="v1.0.0-production-launch",
        predictions=predictions
    )


