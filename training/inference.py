BASE_DIR = os.path.dirname(os.path.abspath(__file__))
MODELS_DIR = os.path.join(BASE_DIR, "models")
MODEL_PATH = os.path.join(MODELS_DIR, "student_risk_mlp.pt")
TORCHSCRIPT_PATH = os.path.join(MODELS_DIR, "student_risk_mlp.torchscript.pt")
SCALER_PATH = os.path.join(MODELS_DIR, "scaler.pkl")
META_PATH = os.path.join(MODELS_DIR, "metadata.json")
EVAL_PATH = os.path.join(MODELS_DIR, "evaluation_report.json")
CERT_PATH = os.path.join(MODELS_DIR, "launch_readiness_certificate.json")

MODEL_LIMITATION_NOTICE = (
    "Model Limitation Notice: Risk classifications generated by EdUGaP AI are advisory screening indicators "
    "intended exclusively to support proactive educator mentorship and remedial study plan formulation. "
    "Under institutional policy, model predictions MUST NOT be used as the sole basis for academic grades, "
    "disciplinary actions, or admission/dismissal decisions."
)

# Global model state
_model = None
_torchscript_model = None
_scaler = None
_metadata = None
_eval_report = None
_feature_weights = None


def load_artifacts():
    global _model, _torchscript_model, _scaler, _metadata, _eval_report, _feature_weights
    if os.path.exists(MODEL_PATH) and os.path.exists(SCALER_PATH):
        try:
            _scaler = joblib.load(SCALER_PATH)
            checkpoint = torch.load(MODEL_PATH, map_location="cpu")
            _model = StudentRiskMLP(input_dim=checkpoint["input_dim"], num_classes=checkpoint["num_classes"])
            _model.load_state_dict(checkpoint["model_state_dict"])
            _model.eval()

            # Attempt TorchScript load
            if os.path.exists(TORCHSCRIPT_PATH):
                try:
                    _torchscript_model = torch.jit.load(TORCHSCRIPT_PATH, map_location="cpu")
                    _torchscript_model.eval()
                except Exception:
                    _torchscript_model = None

            if os.path.exists(META_PATH):
                with open(META_PATH, "r") as f:
                    _metadata = json.load(f)

            if os.path.exists(EVAL_PATH):
                with open(EVAL_PATH, "r") as f:
                    _eval_report = json.load(f)
                    _feature_weights = _eval_report.get("feature_importance_weights", {})

            print("[INFO] Launch-ready PyTorch MLP and production artifacts loaded successfully.")
        except Exception as e:
            print(f"[WARNING] Could not load PyTorch checkpoint ({e}). Rule fallback active.")
            _model = None
            _scaler = None


@app.on_event("startup")
def startup_event():
    load_artifacts()


class StudentFeatureSnapshot(BaseModel):
    student_id: Optional[str] = Field(default=None, description="Optional student identifier (never used in inference)")
    previous_assessment_avg: float = Field(..., ge=0.0, le=100.0, description="Historical average score")
    recent_assessment_score: float = Field(..., ge=0.0, le=100.0, description="Score on most recent assessment")
    topic_wise_accuracy: float = Field(..., ge=0.0, le=100.0, description="Overall topic mastery percentage")
    quiz_completion_rate: float = Field(..., ge=0.0, le=100.0, description="Percentage of assigned quizzes finished")
    attendance_percentage: float = Field(..., ge=0.0, le=100.0, description="Classroom attendance rate")
    assignment_completion_rate: float = Field(..., ge=0.0, le=100.0, description="Homework submission rate")
    study_session_completion_rate: float = Field(..., ge=0.0, le=100.0, description="Adherence to prescribed study plan")
    avg_daily_study_time_minutes: float = Field(..., ge=0.0, description="Average self-study duration per day")
    late_submissions_count: int = Field(..., ge=0, description="Total assignments submitted past deadline")
    integrity_events_count: int = Field(..., ge=0, description="Anti-cheat integrity incidents detected")
    weak_topics_count: int = Field(..., ge=0, description="Number of topics below 60% mastery")
    assessment_attempt_count: int = Field(..., ge=0, description="Total assessments attempted to date")


class FeatureAttribution(BaseModel):
    feature: str
    label: str
    impact_pct: float
    risk_direction: str  # "increases_risk", "mitigates_risk", "neutral"


class RiskPredictionResponse(BaseModel):
    student_id: Optional[str] = None
    risk_level: str
    confidence_score: float
    probabilities: Dict[str, float]
    model_version: str
    production_ready: bool
    fallback_used: bool
    explanation_factors: List[str]
    feature_attributions: List[FeatureAttribution]
    model_limitation_notice: str


class BatchPredictionRequest(BaseModel):
    cohort_name: Optional[str] = Field(default="Classroom Cohort", description="Cohort or class identifier")
    students: List[StudentFeatureSnapshot]


class BatchPredictionResponse(BaseModel):
    cohort_name: str
    total_evaluated: int
    summary: Dict[str, int]
    model_version: str
    predictions: List[RiskPredictionResponse]


def generate_attributions(snapshot: StudentFeatureSnapshot) -> List[FeatureAttribution]:
    """
    Computes individualized Explainable AI (XAI) feature impact for this student
    using base empirical feature weights and actual value deviations.
    """
    weights = _feature_weights or {
        "weak_topics_count": 30.4,
        "late_submissions_count": 16.2,
        "integrity_events_count": 15.2,
        "recent_assessment_score": 12.9,
        "previous_assessment_avg": 9.1,
        "attendance_percentage": 7.5,
        "quiz_completion_rate": 4.5,
        "study_session_completion_rate": 4.2
    }

    friendly_labels = {
        "weak_topics_count": "Weak Curriculum Topics",
        "late_submissions_count": "Late Submissions",
        "integrity_events_count": "Integrity Incidents",
        "recent_assessment_score": "Recent Assessment Score",
        "previous_assessment_avg": "Historical Grade Average",
        "attendance_percentage": "Attendance Rate",
        "quiz_completion_rate": "Quiz Completion Rate",
        "study_session_completion_rate": "Study Plan Adherence",
        "avg_daily_study_time_minutes": "Daily Self-Study Duration",
        "assignment_completion_rate": "Assignment Submission Rate"
    }

    attributions = []
    
    # 1. Weak topics
    wt = snapshot.weak_topics_count
    attributions.append(FeatureAttribution(
        feature="weak_topics_count",
        label=friendly_labels.get("weak_topics_count", "Weak Topics"),
        impact_pct=weights.get("weak_topics_count", 25.0),
        risk_direction="increases_risk" if wt >= 3 else ("neutral" if wt >= 1 else "mitigates_risk")
    ))

    # 2. Late submissions
    ls = snapshot.late_submissions_count
    attributions.append(FeatureAttribution(
        feature="late_submissions_count",
        label=friendly_labels.get("late_submissions_count", "Late Submissions"),
        impact_pct=weights.get("late_submissions_count", 15.0),
        risk_direction="increases_risk" if ls >= 2 else "mitigates_risk"
    ))

    # 3. Integrity events
    ie = snapshot.integrity_events_count
    attributions.append(FeatureAttribution(
        feature="integrity_events_count",
        label=friendly_labels.get("integrity_events_count", "Integrity Events"),
        impact_pct=weights.get("integrity_events_count", 15.0),
        risk_direction="increases_risk" if ie >= 1 else "mitigates_risk"
    ))

    # 4. Recent assessment score
    rs = snapshot.recent_assessment_score
    attributions.append(FeatureAttribution(
        feature="recent_assessment_score",
        label=friendly_labels.get("recent_assessment_score", "Recent Assessment"),
        impact_pct=weights.get("recent_assessment_score", 12.0),
        risk_direction="increases_risk" if rs < 60.0 else "mitigates_risk"
    ))

    # 5. Attendance
    att = snapshot.attendance_percentage
    attributions.append(FeatureAttribution(
        feature="attendance_percentage",
        label=friendly_labels.get("attendance_percentage", "Attendance"),
        impact_pct=weights.get("attendance_percentage", 8.0),
        risk_direction="increases_risk" if att < 75.0 else "mitigates_risk"
    ))

    return sorted(attributions, key=lambda a: a.impact_pct, reverse=True)


def generate_explanation_factors(features: StudentFeatureSnapshot) -> List[str]:
    factors = []
    if features.weak_topics_count >= 3:
        factors.append(f"{features.weak_topics_count} identified weak topics requiring immediate intervention")
    if features.recent_assessment_score < 50.0:
        factors.append(f"Low recent assessment score ({features.recent_assessment_score:.1f}%)")
    if features.attendance_percentage < 75.0:
        factors.append(f"Attendance below institutional standard ({features.attendance_percentage:.1f}%)")
    if features.integrity_events_count >= 2:
        factors.append(f"Multiple anti-cheat integrity flags ({features.integrity_events_count} events)")
    if features.late_submissions_count >= 3:
        factors.append(f"Pattern of late assignment submissions ({features.late_submissions_count})")
    if features.study_session_completion_rate < 50.0:
        factors.append(f"Low study session completion rate ({features.study_session_completion_rate:.1f}%)")

    if not factors:
        if features.recent_assessment_score >= 80.0 and features.attendance_percentage >= 90.0:
            factors.append("Strong academic performance and consistent classroom attendance")
            factors.append("High adherence to personalized study schedule")
        else:
            factors.append("Satisfactory progress across academic and behavioral indicators")

    return factors


def rule_based_fallback(features: StudentFeatureSnapshot) -> RiskPredictionResponse:
    score = (
        0.30 * (features.recent_assessment_score / 100.0) +
        0.20 * (features.previous_assessment_avg / 100.0) +
        0.20 * (features.attendance_percentage / 100.0) +
        0.15 * (features.assignment_completion_rate / 100.0) +
        0.15 * (features.study_session_completion_rate / 100.0) -
        0.05 * min(features.late_submissions_count, 4) -
        0.06 * min(features.integrity_events_count, 4) -
        0.05 * min(features.weak_topics_count, 4)
    )

    if score < 0.52 or features.attendance_percentage < 65.0 or features.weak_topics_count >= 4:
        risk = "High Risk"
        probs = {"Low Risk": 0.05, "Medium Risk": 0.15, "High Risk": 0.80}
        conf = 0.80
    elif score < 0.74:
        risk = "Medium Risk"
        probs = {"Low Risk": 0.20, "Medium Risk": 0.65, "High Risk": 0.15}
        conf = 0.65
    else:
        risk = "Low Risk"
        probs = {"Low Risk": 0.85, "Medium Risk": 0.12, "High Risk": 0.03}
        conf = 0.85

    return RiskPredictionResponse(
        student_id=features.student_id,
        risk_level=risk,
        confidence_score=conf,
        probabilities=probs,
        model_version="v1.0.0-rule-fallback",
        production_ready=False,
        fallback_used=True,
        explanation_factors=generate_explanation_factors(features),
        feature_attributions=generate_attributions(features),
        model_limitation_notice=MODEL_LIMITATION_NOTICE
    )


